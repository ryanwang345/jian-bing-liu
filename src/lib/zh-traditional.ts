export function toTraditionalChinese(text: string): string {
  if (!text) return text;
  let result = text;
  for (const [from, to] of PHRASE_MAP) {
    if (result.includes(from)) {
      result = result.split(from).join(to);
    }
  }
  let out = "";
  for (const ch of result) {
    out += CHAR_MAP[ch] ?? ch;
  }
  return out;
}
